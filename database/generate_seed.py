"""
Generates seed_routes.sql (Coimbatore stops, routes, fleet and 4 weeks of hourly
boarding history). Run:  python generate_seed.py
Uses only the standard library. A fixed random seed keeps output reproducible.
"""
import random
from datetime import date, timedelta

random.seed(38)  # Coimbatore RTO code

STOPS = [  # id, name, lat, lng, zone
    (1, "Gandhipuram Bus Stand", 11.0183, 76.9674, "Central"),
    (2, "Town Hall", 11.0010, 76.9610, "Central"),
    (3, "Ukkadam Bus Stand", 10.9886, 76.9603, "South"),
    (4, "Singanallur", 10.9990, 77.0270, "East"),
    (5, "Peelamedu", 11.0245, 77.0190, "East"),
    (6, "RS Puram", 11.0070, 76.9500, "West"),
    (7, "Saravanampatti", 11.0780, 77.0020, "North"),
    (8, "Vadavalli", 11.0260, 76.9070, "West"),
    (9, "Hope College", 11.0245, 77.0300, "East"),
    (10, "Podanur", 10.9650, 76.9930, "South"),
    (11, "Kuniyamuthur", 10.9600, 76.9620, "South"),
    (12, "Race Course", 11.0000, 76.9740, "Central"),
    (13, "Lakshmi Mills", 11.0150, 76.9900, "Central"),
    (14, "Coimbatore Airport", 11.0300, 77.0430, "East"),
    (15, "Ganapathy", 11.0480, 76.9920, "North"),
    (16, "Thudiyalur", 11.0780, 76.9420, "North"),
    (19, "Ondipudur", 10.9990, 77.0400, "East"),
    (20, "Kovaipudur", 10.9390, 76.9340, "South"),
]

ROUTES = [  # id, number, name, base fare, per stop, stop ids, peak riders/hour
    (1, "1A", "Gandhipuram - Kuniyamuthur", 4, 2.5, [1, 2, 3, 11], 300),
    (2, "12", "Gandhipuram - Ondipudur via Singanallur", 4, 2.5, [1, 13, 4, 19], 260),
    (3, "20", "Gandhipuram - Saravanampatti", 4, 2.5, [1, 15, 7], 230),
    (4, "70", "Ukkadam - Airport via Peelamedu", 4, 2.5, [3, 2, 13, 5, 9, 14], 340),
    (5, "S5", "Vadavalli - Ganapathy via RS Puram", 4, 2.5, [8, 6, 1, 15], 200),
    (6, "S10", "Podanur - Gandhipuram", 4, 2.5, [10, 3, 2, 12, 1], 320),
    (7, "T7", "Kovaipudur - Thudiyalur", 4, 2.5, [20, 11, 3, 2, 1, 16], 150),
]

# (reg, capacity, type, route, status)  -> 3 buses per route + 2 idle reserve
BUS_TYPES = [("ORDINARY", 60), ("EXPRESS", 50), ("AC", 45)]

WEEKDAY = {5: .08, 6: .2, 7: .55, 8: 1.0, 9: .85, 10: .5, 11: .4, 12: .45, 13: .45, 14: .4,
           15: .5, 16: .7, 17: .95, 18: 1.0, 19: .7, 20: .4, 21: .25, 22: .12, 23: .05}
WEEKEND = {5: .05, 6: .1, 7: .2, 8: .35, 9: .5, 10: .65, 11: .75, 12: .8, 13: .75, 14: .7,
           15: .75, 16: .85, 17: .9, 18: .85, 19: .7, 20: .5, 21: .35, 22: .2, 23: .08}

out = ["-- TransitIQ seed data (generated by generate_seed.py)",
       "-- Safe to run repeatedly: INSERT IGNORE + fixed ids.", ""]

out.append("INSERT IGNORE INTO bus_stops (id, name, latitude, longitude, zone) VALUES")
out.append(",\n".join(f"({i}, '{n}', {la}, {lo}, '{z}')" for i, n, la, lo, z in STOPS) + ";\n")

out.append("INSERT IGNORE INTO routes (id, route_number, name, base_fare, fare_per_stop) VALUES")
out.append(",\n".join(f"({i}, '{n}', '{nm}', {b}, {p})" for i, n, nm, b, p, _, _ in ROUTES) + ";\n")

out.append("DELETE FROM route_stops;")
rows = [f"({rid}, {sid}, {order})" for rid, _, _, _, _, stops, _ in ROUTES for order, sid in enumerate(stops)]
out.append("INSERT INTO route_stops (route_id, stop_id, stop_order) VALUES\n" + ",\n".join(rows) + ";\n")

bus_rows, bus_id = [], 1
for rid, num, _, _, _, stops, _ in ROUTES:
    n = len(stops) - 1
    for k in range(3):
        btype, cap = BUS_TYPES[(rid + k) % 3]
        direction = 1 if k % 2 == 0 else -1
        progress = round(n * (k + 0.5) / 3, 2)
        onboard = int(cap * random.uniform(0.2, 0.6))
        reg = f"TN 38 N {1000 + bus_id}"
        bus_rows.append(f"({bus_id}, '{reg}', {cap}, '{btype}', 'RUNNING', {rid}, {progress}, {direction}, {onboard}, NULL, NULL)")
        bus_id += 1
for reserve in range(2):  # idle reserve fleet at the depot
    bus_rows.append(f"({bus_id}, 'TN 38 N {1000 + bus_id}', 60, 'ORDINARY', 'IDLE', NULL, 0, 1, 0, NULL, NULL)")
    bus_id += 1
out.append("INSERT IGNORE INTO buses (id, registration_no, capacity, bus_type, status, route_id, progress, direction, passengers_onboard, current_lat, current_lng) VALUES")
out.append(",\n".join(bus_rows) + ";\n")

# 4 weeks of history: one weekday (Mon) and one weekend day (Sun) per week
base_monday = date(2026, 10, 26)
demand, rec_id = [], 1
for rid, _, _, _, _, _, peak in ROUTES:
    for week in range(4):
        for day_type, profile, day, scale in (
                ("WEEKDAY", WEEKDAY, base_monday - timedelta(weeks=week), 1.0),
                ("WEEKEND", WEEKEND, base_monday - timedelta(days=1, weeks=week), 0.75)):
            for hour, weight in profile.items():
                riders = max(0, round(peak * scale * weight * random.gauss(1.0, 0.08)))
                demand.append(f"({rec_id}, {rid}, '{day_type}', {hour}, {riders}, '{day.isoformat()}')")
                rec_id += 1

out.append("INSERT IGNORE INTO demand_records (id, route_id, day_type, hour_of_day, passengers, recorded_on) VALUES")
chunks = [demand[i:i + 200] for i in range(0, len(demand), 200)]
out.append("\n".join(
    (",\n".join(c) + ";\n") if idx == len(chunks) - 1 else
    (",\n".join(c) + ";\n\nINSERT IGNORE INTO demand_records (id, route_id, day_type, hour_of_day, passengers, recorded_on) VALUES")
    for idx, c in enumerate(chunks)))

with open("seed_routes.sql", "w", encoding="utf-8") as f:
    f.write("\n".join(out))
print(f"Wrote seed_routes.sql: {len(STOPS)} stops, {len(ROUTES)} routes, {bus_id - 1} buses, {len(demand)} demand rows")
